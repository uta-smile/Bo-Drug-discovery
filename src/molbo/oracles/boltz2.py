"""Realism tier: Boltz-2 co-folding affinity as an expensive, structure-based oracle.

This tier is where the method is *shown to survive*, not where it is developed.
At roughly 20 s/ligand it is three to four orders of magnitude slower than the
lookup tier, so it runs last, on few seeds, on the best method plus plain BO.

It is also the differentiator.  PMO deliberately excluded docking scores as
"more costly than the other oracles while still being coarse estimates that
don't reflect true bioactivity", leaving them to future work.  Boltz-2's
affinity head is a meaningful step past docking, so sample-efficient molecular
BO against a co-folding oracle sits in the gap the benchmark community punted
on.

Determinism
-----------
**Boltz-2 is nondeterministic by default and this oracle makes it deterministic
in two independent ways, because one is not enough.**

*Seed, per ligand.*  ``boltz predict`` takes ``--seed``, but it defaults to
``None`` -- no seeding at all -- so the same molecule re-queried returns a
different number.  That is a different (noisy-oracle) problem from the one this
project studies.  :class:`Boltz2Oracle` derives the seed from a hash of the
molecule's canonical SMILES, so a ligand's value depends on the ligand and
nothing else: not on when it was proposed, not on which molecules it was
batched with, not on which seed the campaign is running.

*Gamma, set to zero.*  The seed alone only makes a run *repeatable*; the
sampler is still a stochastic SDE whose trajectory is pure noise-driven churn.
In Boltz-2's sampler::

    gammas = torch.where(sigmas > gamma_min, gamma_0, 0.0)
    t_hat  = sigma_tm * (1 + gamma)
    noise_var = noise_scale**2 * (t_hat**2 - sigma_tm**2)   # == 0 when gamma == 0

so ``gamma_0 = 0`` makes ``t_hat == sigma_tm``, the injected-noise variance
collapses to exactly zero, and the sampler becomes the deterministic
probability-flow ODE instead of a stochastic one.  Boltz-2's defaults are
``gamma_0 = 0.8``, ``gamma_min = 1.0``.

``gamma_0``/``gamma_min`` are **not** exposed as CLI flags -- only ``step_scale``
is -- so they are applied by patching ``Boltz2DiffusionParams`` in the launched
process before the CLI builds its parameter object. That is why this oracle
shells out through a generated runner instead of calling ``boltz`` directly.

Both knobs are recorded in :attr:`cache_key`, so changing either invalidates
cached values rather than mixing two samplers' numbers in one results table.

Values
------
``affinity_pred_value`` is returned, **negated**.  Boltz-2 reports it as
log10(IC50) in micromolar, where lower is more potent; negating makes the
oracle a maximisation problem consistent with every other tier.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

from .base import Oracle

BOLTZ2_DEFAULT_GAMMA_0 = 0.8
BOLTZ2_DEFAULT_GAMMA_MIN = 1.0


def ligand_seed(smiles: str, salt: str = "") -> int:
    """A stable per-ligand seed derived from canonical SMILES.

    ``hash()`` is deliberately not used: Python randomises string hashing per
    process, so it would give a different seed on every run and silently
    reintroduce exactly the nondeterminism this exists to remove.
    """
    digest = hashlib.sha256(f"{salt}|{smiles}".encode()).digest()
    return int.from_bytes(digest[:4], "big") % (2**31 - 1)


RUNNER_TEMPLATE = '''"""Generated by molbo. Patches Boltz-2 diffusion gamma, then runs the CLI.

gamma_0 / gamma_min are dataclass fields, not CLI options, so they are set on
the class before boltz builds its parameter object. Setting gamma_0 to 0 zeroes
the injected-noise variance and makes the diffusion sampler deterministic.
"""
import sys

import torch

import boltz.main as bm

# VRAM ceiling, enforced in the process that actually allocates. PyTorch's
# caching allocator otherwise grows to fill the card and `nvidia-smi` reports
# the reserved pool, not the live requirement -- so capping the fraction is the
# only way to make "at most N GB" mean anything. Exceeding it raises a normal
# CUDA OOM, which the oracle records as a failed ligand rather than a crash.
_cap_gb = {vram_gb!r}
if _cap_gb and torch.cuda.is_available():
    _total = torch.cuda.get_device_properties(0).total_memory / 1024 ** 3
    torch.cuda.set_per_process_memory_fraction(min(1.0, _cap_gb / _total), 0)

for _cls_name in ("Boltz2DiffusionParams", "BoltzDiffusionParams"):
    _cls = getattr(bm, _cls_name, None)
    if _cls is not None:
        _cls.gamma_0 = {gamma_0!r}
        _cls.gamma_min = {gamma_min!r}

if __name__ == "__main__":
    sys.argv[0] = "boltz"
    bm.cli()
'''


@dataclass
class Boltz2Config:
    """Everything that changes the number Boltz-2 returns.

    Every field here is part of the cache key. If you change one, previously
    cached values are not reused -- which is the point: a results table must
    not silently blend two different samplers.
    """

    protein_sequence: str
    binder_chain: str = "B"
    protein_chain: str = "A"
    msa_path: str | None = None
    """Precomputed MSA (.a3m). Strongly recommended: the target is fixed across
    the whole campaign, so computing it once avoids thousands of identical
    requests to the public MSA server."""

    use_msa_server: bool = False
    diffusion_samples: int = 1
    diffusion_samples_affinity: int = 5
    sampling_steps: int = 200
    sampling_steps_affinity: int = 200
    step_scale: float = 1.5
    recycling_steps: int = 3
    affinity_mw_correction: bool = False
    use_potentials: bool = False

    vram_gb: float | None = None
    """Hard ceiling on GPU memory for the prediction process, in GiB.

    ``None`` lets PyTorch use the whole card. A number caps the per-process
    fraction, so the allocator refuses rather than expands. This is a resource
    limit, not a modelling choice -- it cannot change a value, only whether one
    is produced -- so it is not part of :meth:`key`."""

    max_parallel_samples: int = 1
    """How many affinity diffusion samples share a forward pass.

    This is the dominant VRAM term. Boltz defaults to 5, which runs all five
    of ``diffusion_samples_affinity`` concurrently and pushed a 16 GB card to
    its limit on a 309-residue target. At 1 they run sequentially: the same
    samples, the same arithmetic, roughly a fifth of the activation memory and
    correspondingly slower.

    It is a batching knob, not a modelling one, so it is deliberately **not**
    in :meth:`key` -- values computed at different settings are the same
    values and should share a cache."""

    max_msa_seqs: int = 8192
    subsample_msa: bool = False
    num_subsampled_msa: int = 1024
    """MSA depth. The pairformer is quadratic in sequence length and linear in
    MSA depth, so trimming the alignment is the second lever after
    ``max_parallel_samples``. Unlike that one these **change the input**, and
    therefore the number, so they are part of the cache key."""

    no_kernels: bool = False
    """Disable the fused triangular-multiplication CUDA kernels.

    The kernels come from ``cuequivariance-ops-torch-cu12``, which publishes
    Linux wheels only, so on Windows the import fails inside the model's
    forward pass and every ligand returns ``None``. This falls back to the pure
    PyTorch path: slower, same arithmetic. It is part of the cache key because
    "same arithmetic" is a claim about the implementation, not a guarantee, and
    a results table must not silently blend the two."""

    gamma_0: float = 0.0
    """Diffusion churn. ``0`` removes injected noise entirely (deterministic ODE)."""
    gamma_min: float = 0.0

    seed_salt: str = ""
    """Change to re-draw every per-ligand seed -- the explicit way to run a
    noisy-oracle arm without pretending it is the same oracle."""

    accelerator: str = "gpu"
    devices: int = 1
    checkpoint: str | None = None
    affinity_checkpoint: str | None = None

    def key(self) -> str:
        parts = [
            hashlib.sha256(self.protein_sequence.encode()).hexdigest()[:12],
            f"ds={self.diffusion_samples}",
            f"dsa={self.diffusion_samples_affinity}",
            f"ss={self.sampling_steps}",
            f"ssa={self.sampling_steps_affinity}",
            f"scale={self.step_scale}",
            f"rec={self.recycling_steps}",
            f"g0={self.gamma_0}",
            f"gmin={self.gamma_min}",
            f"mw={int(self.affinity_mw_correction)}",
            f"pot={int(self.use_potentials)}",
            f"nok={int(self.no_kernels)}",
            f"msa={self.max_msa_seqs}",
            f"sub={int(self.subsample_msa)}:{self.num_subsampled_msa}",
            f"salt={self.seed_salt}",
        ]
        if self.checkpoint:
            parts.append("ckpt=" + Path(self.checkpoint).name)
        if self.affinity_checkpoint:
            parts.append("affckpt=" + Path(self.affinity_checkpoint).name)
        return "|".join(parts)

    @property
    def is_deterministic(self) -> bool:
        return self.gamma_0 == 0.0


class Boltz2Oracle(Oracle):
    """Score ligands against a fixed protein with Boltz-2's affinity head.

    Parameters
    ----------
    config:
        The prediction settings. Defaults are the deterministic ones.
    work_dir:
        Where YAML inputs and Boltz outputs go. Defaults to a temp directory
        cleaned up on close; pass a real path to keep the structures.
    cache_path:
        SQLite value cache. Strongly recommended -- 20 seeds over one library
        overlap heavily, and this is the difference between 90 GPU-hours and an
        afternoon.
    value:
        ``affinity_pred_value`` (default, negated -- the SAR quantity, for
        hit-to-lead and lead-optimisation) or ``affinity_probability_binary``
        (binder-vs-decoy, for hit discovery; not negated).
    """

    def __init__(
        self,
        config: Boltz2Config,
        *,
        name: str = "boltz2",
        work_dir: str | Path | None = None,
        keep_outputs: bool = False,
        value: str = "affinity_pred_value",
        boltz_python: str | None = None,
        timeout: int = 1800,
        **kwargs,
    ):
        if value not in ("affinity_pred_value", "affinity_probability_binary"):
            raise ValueError(
                "value must be 'affinity_pred_value' or 'affinity_probability_binary'"
            )
        self.config = config
        self.value_field = value
        self.keep_outputs = keep_outputs
        self.timeout = timeout
        self.boltz_python = boltz_python or sys.executable

        self._tmp = None
        if work_dir is None:
            self._tmp = tempfile.mkdtemp(prefix="molbo_boltz2_")
            work_dir = self._tmp
        self.work_dir = Path(work_dir)
        self.work_dir.mkdir(parents=True, exist_ok=True)

        self._runner = self.work_dir / "_boltz_runner.py"
        self._runner.write_text(
            RUNNER_TEMPLATE.format(gamma_0=config.gamma_0,
                                   gamma_min=config.gamma_min,
                                   vram_gb=config.vram_gb),
            encoding="utf-8",
        )

        kwargs.setdefault("maximize", True)
        super().__init__(name, **kwargs)

    # ---- identity ---------------------------------------------------------

    @property
    def cache_key(self) -> str:
        return f"{super().cache_key}|{self.value_field}|{self.config.key()}"

    def describe(self) -> dict:
        d = super().describe()
        d.update(
            value_field=self.value_field,
            negated=self.value_field == "affinity_pred_value",
            deterministic=self.config.is_deterministic,
            seed_policy="sha256(canonical_smiles) per ligand",
            gamma_0=self.config.gamma_0,
            gamma_min=self.config.gamma_min,
            boltz2_default_gamma_0=BOLTZ2_DEFAULT_GAMMA_0,
            boltz2_default_gamma_min=BOLTZ2_DEFAULT_GAMMA_MIN,
            config=self.config.key(),
        )
        return d

    # ---- input ------------------------------------------------------------

    def _write_yaml(self, path: Path, smiles: str) -> None:
        cfg = self.config
        lines = ["version: 1", "sequences:", "  - protein:", f"      id: {cfg.protein_chain}"]
        lines.append(f"      sequence: {cfg.protein_sequence}")
        if cfg.msa_path:
            lines.append(f"      msa: {cfg.msa_path}")
        lines += [
            "  - ligand:",
            f"      id: {cfg.binder_chain}",
            # Single-quoted: SMILES routinely contains ':', '#' and '[', all of
            # which are YAML syntax unquoted.
            f"      smiles: '{smiles}'",
            "properties:",
            "  - affinity:",
            f"      binder: {cfg.binder_chain}",
        ]
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    def _command(self, yaml_path: Path, out_dir: Path, seed: int) -> list[str]:
        cfg = self.config
        cmd = [
            self.boltz_python,
            str(self._runner),
            "predict",
            str(yaml_path),
            "--out_dir", str(out_dir),
            "--seed", str(seed),
            "--diffusion_samples", str(cfg.diffusion_samples),
            "--diffusion_samples_affinity", str(cfg.diffusion_samples_affinity),
            "--sampling_steps", str(cfg.sampling_steps),
            "--sampling_steps_affinity", str(cfg.sampling_steps_affinity),
            "--step_scale", str(cfg.step_scale),
            "--recycling_steps", str(cfg.recycling_steps),
            "--max_parallel_samples", str(cfg.max_parallel_samples),
            "--max_msa_seqs", str(cfg.max_msa_seqs),
            "--accelerator", cfg.accelerator,
            "--devices", str(cfg.devices),
            "--output_format", "pdb",
        ]
        if cfg.use_msa_server:
            cmd.append("--use_msa_server")
        if cfg.affinity_mw_correction:
            cmd.append("--affinity_mw_correction")
        if cfg.use_potentials:
            cmd.append("--use_potentials")
        if cfg.no_kernels:
            cmd.append("--no_kernels")
        if cfg.subsample_msa:
            cmd += ["--subsample_msa",
                    "--num_subsampled_msa", str(cfg.num_subsampled_msa)]
        if cfg.checkpoint:
            cmd += ["--checkpoint", cfg.checkpoint]
        if cfg.affinity_checkpoint:
            cmd += ["--affinity_checkpoint", cfg.affinity_checkpoint]
        return cmd

    # ---- evaluation -------------------------------------------------------

    def _evaluate_batch(self, smiles: Sequence[str]) -> Sequence[float | None]:
        """One Boltz invocation per ligand, each with its own seed.

        Not batched on purpose. ``--seed`` is per *invocation*, so a batched
        run would share one RNG stream across its members and a molecule's
        value would depend on what it happened to be batched with -- exactly
        the nondeterminism the per-ligand seed exists to remove. Model loading
        is re-paid per ligand; the cross-run SQLite cache is what makes that
        affordable over a multi-seed sweep.
        """
        return [self._run_one(s) for s in smiles]

    def _run_one(self, smiles: str) -> float | None:
        seed = ligand_seed(smiles, self.config.seed_salt)
        stem = hashlib.sha256(smiles.encode()).hexdigest()[:16]
        job_dir = self.work_dir / stem
        job_dir.mkdir(parents=True, exist_ok=True)
        yaml_path = job_dir / f"{stem}.yaml"
        self._write_yaml(yaml_path, smiles)

        cmd = self._command(yaml_path, job_dir, seed)
        try:
            # Expandable segments let the caching allocator give blocks back
            # instead of holding a fragmented pool, which on a 16 GB card is
            # the difference between finishing and an OOM two ligands in.
            env = dict(os.environ)
            env.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")
            proc = subprocess.run(
                cmd, capture_output=True, text=True, timeout=self.timeout,
                check=False, env=env,
            )
        except subprocess.TimeoutExpired:
            self._note_failure(job_dir, smiles, seed, "timeout", "")
            return None

        result = job_dir / f"boltz_results_{stem}" / "predictions" / stem / f"affinity_{stem}.json"
        if not result.exists():
            self._note_failure(job_dir, smiles, seed, f"exit={proc.returncode}", proc.stderr)
            return None

        payload = json.loads(result.read_text(encoding="utf-8"))
        raw = payload.get(self.value_field)
        if raw is None:
            self._note_failure(job_dir, smiles, seed, "missing field", "")
            return None

        # affinity_pred_value is log10(IC50) in uM: lower is more potent, so
        # negate to make every tier a maximisation.
        value = -float(raw) if self.value_field == "affinity_pred_value" else float(raw)

        if not self.keep_outputs:
            shutil.rmtree(job_dir, ignore_errors=True)
        return value

    def _note_failure(self, job_dir: Path, smiles: str, seed: int, reason: str,
                      stderr: str | None) -> None:
        """Record a failure next to the job rather than raising.

        A single ligand Boltz cannot fold must not kill a 200-call campaign.
        The base class stores the ``None`` in the value cache, so a
        deterministic failure is not retried on every subsequent seed.
        """
        # `stderr` is optional: a timeout captures none, and neither does a
        # missing field in an otherwise successful run. Slicing it unguarded
        # turned every such failure into a TypeError raised *from inside the
        # reporter*, which buried the original reason under a stack trace
        # pointing at the wrong place.
        tail = (stderr or "")[-4000:] or "(no stderr captured)"
        (job_dir / "FAILED.txt").write_text(
            f"smiles: {smiles}\nseed: {seed}\nreason: {reason}\n\n{tail}",
            encoding="utf-8",
        )

    # ---- lifecycle --------------------------------------------------------

    def close(self) -> None:
        if self._tmp and not self.keep_outputs:
            shutil.rmtree(self._tmp, ignore_errors=True)


def check_boltz_available(python: str | None = None) -> tuple[bool, str]:
    """``(available, detail)`` -- whether Boltz can be imported by ``python``."""
    python = python or sys.executable
    try:
        proc = subprocess.run(
            [python, "-c", "import boltz; print(getattr(boltz, '__version__', 'unknown'))"],
            capture_output=True,
            text=True,
            timeout=120,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:  # pragma: no cover
        return False, str(exc)
    if proc.returncode == 0:
        return True, proc.stdout.strip()
    return False, proc.stderr.strip()
