"""Decompose the history-design effect into artefact and information parts.

The design effect is (preferential history) minus (uniform history), measured in
Recall@10 points relative to ``stl`` and averaged over targets and repeats
inside a family.  Under randomized auxiliary responses (``q0``) no auxiliary
*value* carries information, so whatever design effect survives there is pure
artefact -- the paper's C1 logic applied to the design axis instead of to the
level.  The information component is then the q1 effect minus the q0 effect.

Additivity is an approximation, and it is the same approximation C1 already
makes elsewhere in the manuscript.

Writes ``report/generated/macros_decomp.tex``.  Run from the repository root:

    python scripts/decompose_design.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from scipy.stats import t, wilcoxon

ROOT = Path(__file__).resolve().parents[1]
SWEEP = ROOT / "results" / "family_sweep"
OUT = ROOT / "report" / "generated" / "macros_decomp.tex"
# Per-family breakdown behind the main-text table, for the supplement only.
OUT_TABLE = ROOT / "report" / "generated" / "table_decomp_families.tex"

FAMILIES = ("mmp", "dpp", "cyp", "hdac", "pi3k", "jak")
# Arms reported in the decomposition table, in the order they appear there.
ARMS = ("stl_avoid", "pooled", "mt", "basis")
# Arms that read no auxiliary *value*; randomizing those values must leave them
# untouched.  If that ever fails, the q0 column is not measuring an artefact.
VALUE_FREE = ("stl", "stl_avoid", "basis_chem")


def recalls(fam: str, design: str, q: str, arm: str) -> np.ndarray:
    """Per-campaign Recall@10 in percentage points."""
    path = SWEEP / f"fam_{fam}_{design}_{q}.json"
    with path.open() as fh:
        return np.asarray(json.load(fh)["arms"][arm]["recall"], float) * 100.0


def gain(fam: str, design: str, q: str, arm: str) -> float:
    """Mean Recall@10 gain over ``stl`` within one family-design-q cell."""
    return float((recalls(fam, design, q, arm)
                  - recalls(fam, design, q, "stl")).mean())


def summarise(values: np.ndarray) -> dict[str, str]:
    """Family-level mean, t interval, Wilcoxon p, and sign count.

    Signed quantities are wrapped in math mode so that a negative sign sets as
    a proper minus rather than a hyphen, matching the hand-written figures
    elsewhere in the manuscript.  The p-value and the count are left bare,
    because they are already quoted inside math mode at their use sites.
    """
    n = len(values)
    mean = values.mean()
    if np.allclose(values, 0.0):
        return {"": f"${mean:+.2f}$", "Ci": "$[+0.00,+0.00]$",
                "P": "1.000", "Positive": "0"}
    half = t.ppf(0.975, n - 1) * values.std(ddof=1) / np.sqrt(n)
    p = wilcoxon(values, alternative="two-sided", method="auto").pvalue
    return {"": f"${mean:+.2f}$",
            "Ci": f"$[{mean - half:+.2f},{mean + half:+.2f}]$",
            "P": f"{p:.3f}",
            "Positive": str(int((values > 0).sum()))}


def camel(arm: str) -> str:
    """``stl_avoid`` -> ``StlAvoid``; LaTeX macro names take no digits either."""
    return "".join(part.capitalize() for part in arm.split("_"))


def main() -> None:
    lines = ["% Generated by scripts/decompose_design.py; do not edit."]

    # Internal validity: value-free arms must be bit-identical across q.
    worst = 0.0
    for arm in VALUE_FREE:
        for fam in FAMILIES:
            for design in ("uniform", "pref1"):
                a = recalls(fam, design, "q1", arm)
                b = recalls(fam, design, "q0", arm)
                worst = max(worst, float(np.abs(a - b).max()))
    if worst != 0.0:
        raise SystemExit(
            f"internal validity FAILED: value-free arms differ by {worst:.4g} "
            "between measured and randomized auxiliary responses, so the q0 "
            "column cannot be read as a pure artefact")
    lines.append("\\newcommand{\\decompValidityArms}{%d}" % len(VALUE_FREE))

    for arm in ARMS:
        total, artefact = [], []
        for fam in FAMILIES:
            total.append(gain(fam, "pref1", "q1", arm) - gain(fam, "uniform", "q1", arm))
            artefact.append(gain(fam, "pref1", "q0", arm) - gain(fam, "uniform", "q0", arm))
        total = np.asarray(total)
        artefact = np.asarray(artefact)
        parts = {"Total": total, "Artefact": artefact,
                 "Information": total - artefact}
        for name, values in parts.items():
            for suffix, text in summarise(values).items():
                lines.append(
                    f"\\newcommand{{\\decomp{camel(arm)}{name}{suffix}}}{{{text}}}")

    # Head-to-head, so no arm is claimed better than it is.  LaTeX macro names
    # take letters only, so "pref1" cannot go into one verbatim.
    for design, label in (("uniform", "Uniform"), ("pref1", "Preferential")):
        values = np.asarray([gain(f, design, "q1", "basis") - gain(f, design, "q1", "mt")
                             for f in FAMILIES])
        for suffix, text in summarise(values).items():
            lines.append(
                f"\\newcommand{{\\decompBasisMinusMt{label}{suffix}}}{{{text}}}")

    lines.append("\\newcommand{\\decompFamilies}{%d}" % len(FAMILIES))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(lines) - 1} macros)")

    # Per-family breakdown, three rows per arm, one column per family.
    pretty = {"stl_avoid": "Avoidance only", "pooled": "\\pooled{}",
              "mt": "\\mt{}", "basis": "\\basis{}"}
    rows = ["% Generated by scripts/decompose_design.py; do not edit.",
            "\\begin{tabular}{llrrrrrrr}", "\\toprule",
            "Arm & Component & " + " & ".join(f.upper() for f in FAMILIES)
            + " & Mean \\\\", "\\midrule"]
    for k, arm in enumerate(ARMS):
        total = np.asarray([gain(f, "pref1", "q1", arm) - gain(f, "uniform", "q1", arm)
                            for f in FAMILIES])
        artefact = np.asarray([gain(f, "pref1", "q0", arm) - gain(f, "uniform", "q0", arm)
                               for f in FAMILIES])
        for j, (name, values) in enumerate((("Total", total),
                                            ("Artefact", artefact),
                                            ("Information", total - artefact))):
            label = pretty[arm] if j == 0 else ""
            cells = " & ".join(f"${v:+.2f}$" for v in values)
            rows.append(f"{label} & {name} & {cells} & ${values.mean():+.2f}$ \\\\")
        if k < len(ARMS) - 1:
            rows.append("\\midrule")
    rows += ["\\bottomrule", "\\end{tabular}"]
    OUT_TABLE.write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"wrote {OUT_TABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
