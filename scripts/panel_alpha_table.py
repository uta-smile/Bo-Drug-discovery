"""Tabulate where real BindingDB panels sit on the history-design axis.

Reads ``results/panel_propensity.json`` (written by ``scripts/panel_propensity.py``)
and emits the supplement table plus the handful of macros the manuscript quotes.

Two scale-free statistics describe a real panel: the standardized mean
difference (SMD) between the auxiliary activity of panel and non-panel
compounds, and the top-$k$ capture lift, the share of the primary target's $k$
best compounds that the panel holds divided by the panel's library coverage.
Each is compared against a simulated curve generated at *that panel's own
coverage*, because capture lift is bounded above by the reciprocal of coverage
and curves at different coverages are not comparable. Inverting the curve gives
the $\\alpha$ of the preferential design that would reproduce the observed
statistic.

Run from the repository root:

    python scripts/panel_alpha_table.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "results" / "panel_propensity.json"
OUT_TABLE = ROOT / "report" / "generated" / "table_panel_alpha.tex"
OUT_MACROS = ROOT / "report" / "generated" / "macros_panel_alpha.tex"

FILTERS = ("low", "none", "all")


def num(value: float | None, places: int = 2, signed: bool = True) -> str:
    """A LaTeX math cell, or an em dash where the statistic did not resolve."""
    if value is None:
        return "---"
    return f"${value:{'+' if signed else ''}.{places}f}$"


def main() -> None:
    with SRC.open() as fh:
        blob = json.load(fh)
    families, settings = blob["families"], blob["settings"]

    rows = ["% Generated by scripts/panel_alpha_table.py; do not edit.",
            "\\begin{tabular}{llrrrrrrrr}", "\\toprule",
            "& & & \\multicolumn{3}{c}{SMD} & \\multicolumn{3}{c}{Capture lift} "
            "& \\multicolumn{1}{c}{} \\\\",
            "\\cmidrule(lr){4-6}\\cmidrule(lr){7-9}",
            "Family & Target & Cov. & low & none & all & low & none & all "
            "& $\\alpha$ \\\\", "\\midrule"]

    alphas, n_rows, n_alpha = [], 0, 0
    for fam, fdata in families.items():
        by_filter = fdata["real_by_filter"]
        # Index every filter's rows by target so the three rules line up.
        index = {f: {r["label"]: r for r in by_filter[f]} for f in FILTERS}
        first = True
        for entry in by_filter["low"]:
            label = entry["label"]
            if entry.get("skipped") or not entry.get("reliable"):
                continue  # Coverage too high for the statistic to resolve.
            n_rows += 1
            smd = [index[f].get(label, {}).get("smd") for f in FILTERS]
            lift = [index[f].get(label, {}).get("capture_lift") for f in FILTERS]
            a_smd = entry.get("alpha_from_smd")
            a_lift = entry.get("alpha_from_lift")
            shown = [a for a in (a_smd, a_lift) if a is not None]
            alphas.extend(shown)
            if shown:
                n_alpha += 1
            alpha_cell = ", ".join(num(a) for a in shown) if shown else "---"
            rows.append(
                f"{fam.upper() if first else ''} & {label} & "
                f"{num(entry['panel_frac'], 2, signed=False)} & "
                + " & ".join(num(v) for v in smd) + " & "
                + " & ".join(num(v, 2, signed=False) for v in lift)
                + f" & {alpha_cell} \\\\")
            first = False
        if not first:
            rows.append("\\midrule")
    rows[-1] = "\\bottomrule"
    rows.append("\\end{tabular}")
    OUT_TABLE.write_text("\n".join(rows) + "\n", encoding="utf-8")

    cyp = next(r for r in families["cyp"]["real_by_filter"]["low"]
               if r["label"] == "CYP3A4")
    macros = [
        "% Generated by scripts/panel_alpha_table.py; do not edit.",
        f"\\newcommand{{\\panelAlphaMin}}{{${min(alphas):+.2f}$}}",
        f"\\newcommand{{\\panelAlphaMax}}{{${max(alphas):+.2f}$}}",
        f"\\newcommand{{\\panelAlphaTargets}}{{{n_alpha}}}",
        f"\\newcommand{{\\panelReliableTargets}}{{{n_rows}}}",
        f"\\newcommand{{\\panelRepeats}}{{{settings['repeats']}}}",
        f"\\newcommand{{\\panelTopK}}{{{settings['k']}}}",
        f"\\newcommand{{\\panelMaxCoverage}}{{{settings['max_panel_frac']:.2f}}}",
        f"\\newcommand{{\\panelCypThreeAFourLift}}"
        f"{{{cyp['capture_lift']:.2f}}}",
        f"\\newcommand{{\\panelCypThreeAFourExpected}}"
        f"{{{cyp['capture_expected']:.1f}}}",
        f"\\newcommand{{\\panelCypThreeAFourCoverage}}"
        f"{{{cyp['panel_frac']:.2f}}}",
    ]
    OUT_MACROS.write_text("\n".join(macros) + "\n", encoding="utf-8")
    print(f"wrote {OUT_TABLE.relative_to(ROOT)} ({n_rows} target rows)")
    print(f"wrote {OUT_MACROS.relative_to(ROOT)} ({len(macros) - 1} macros); "
          f"alpha spans {min(alphas):+.2f} to {max(alphas):+.2f} "
          f"over {n_alpha} targets")


if __name__ == "__main__":
    main()
