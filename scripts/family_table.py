"""Per-family block characteristics for the manuscript's dataset table.

    python scripts/family_table.py --tex report/generated/table_families.tex

A reviewer reading a transfer paper asks first how related the targets
actually are, and the six-family comparison never says. This reads each
family's block straight from the provenance recorded in its campaign
artefact, re-applies the project's own censoring filter, and reports the
pool size and the pairwise target correlations the campaigns actually saw.

Nothing here is re-derived by hand: the block CSV, the censoring parameter
and the target list all come from the stored run, so the table cannot drift
from the experiments it describes.
"""

from __future__ import annotations

import argparse
import glob
import itertools
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from dense_block_h1 import drop_censored  # noqa: E402

# Uniform history is the manuscript's main design, so read the uniform runs.
PATTERN = "results/winleak_*.json"


def families() -> dict[str, dict]:
    """family -> provenance, from the stored campaign artefacts."""
    out: dict[str, dict] = {}
    for f in sorted(glob.glob(str(ROOT / PATTERN))):
        d = json.loads(Path(f).read_text(encoding="utf-8"))
        prov = d.get("provenance") or {}
        if not prov.get("block_csv"):
            continue
        fam = d["family"]
        # Two budgets per family share one block; keep the first and assert the
        # second agrees, so a mismatched pair is caught rather than averaged.
        if fam in out:
            assert out[fam]["block_csv"] == prov["block_csv"], fam
            assert out[fam]["n_pool"] == d["n_pool"], fam
            continue
        out[fam] = {"block_csv": prov["block_csv"], "targets": prov["targets"],
                    "n_block": prov["n_block"], "n_pool": d["n_pool"],
                    "censoring": prov.get("censoring")}
    return out


def row(fam: str, prov: dict) -> dict:
    block = pd.read_csv(ROOT / prov["block_csv"])
    targets = list(prov["targets"])
    missing = int(block[targets].isna().to_numpy().sum())
    kept, _piles = drop_censored(block, targets, pile_frac=0.02, verbose=False)
    rhos = [float(spearmanr(kept[a], kept[b]).statistic)
            for a, b in itertools.combinations(targets, 2)]
    return {
        "family": fam.upper(), "targets": targets,
        "n_block": len(block), "n_pool": len(kept), "stored_pool": prov["n_pool"],
        "missing_entries": missing,
        "rho_median": float(np.median(rhos)),
        "rho_min": float(np.min(rhos)), "rho_max": float(np.max(rhos)),
    }


def coupling_vs_gain(rows: list[dict]) -> dict:
    """Does a family's measured coupling predict how its arms did?

    Post-hoc and over six families, so this is descriptive. It is reported
    because it is the mechanism the pooling result implies: a fully pooled GP
    assumes one shared function, so it should pay where a family nearly is one
    and cost where it is not. The per-cell gains are the published ones.
    """
    cells = json.loads((ROOT / "results" / "summaries.json").read_text("utf-8"))
    by = {s["name"]: s for s in cells if s.get("name")}
    del by  # family means come from the artefacts below, not the aggregate

    gains: dict[str, dict[str, list[float]]] = {}
    for f in sorted(glob.glob(str(ROOT / PATTERN))):
        d = json.loads(Path(f).read_text(encoding="utf-8"))
        arms = d.get("arms") or {}
        base = np.asarray(arms["stl"]["recall"], float)
        for arm in ("mt", "pooled"):
            v = (np.asarray(arms[arm]["recall"], float) - base) * 100.0
            gains.setdefault(d["family"].upper(), {}).setdefault(arm, []).append(
                float(v.mean()))

    fams = [r["family"] for r in rows]
    rho = [r["rho_median"] for r in rows]
    out = {"families": fams, "rho_median": rho}
    for arm in ("mt", "pooled"):
        y = [float(np.mean(gains[f][arm])) for f in fams]
        s = spearmanr(rho, y)
        out[arm] = {"gain": y, "rho": float(s.statistic), "p": float(s.pvalue)}
    return out


def macros(assoc: dict) -> str:
    L = ["% Generated by scripts/family_table.py -- do not edit."]
    for arm, base in (("pooled", "PooledCoupling"), ("mt", "MtCoupling")):
        L.append(f"\\newcommand{{\\rho{base}}}{{${assoc[arm]['rho']:+.3f}$}}")
        L.append(f"\\newcommand{{\\p{base}}}{{${assoc[arm]['p']:.3f}$}}")
    L.append(f"\\newcommand{{\\nCouplingFamilies}}{{{len(assoc['families'])}}}")
    return "\n".join(L) + "\n"


def tex(rows: list[dict]) -> str:
    out = [r"\begin{tabular}{llrrc}", r"\toprule",
           r"Family & Targets & Block & Pool & Pairwise $\rho$ "
           r"(median [min, max]) \\", r"\midrule"]
    for r in rows:
        out.append(
            "%s & \\texttt{%s} & %s & %s & %.2f [%.2f, %.2f] \\\\"
            % (r["family"], ", ".join(r["targets"]).replace("_", r"\_"),
               f'{r["n_block"]:,}', f'{r["n_pool"]:,}',
               r["rho_median"], r["rho_min"], r["rho_max"]))
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tex", type=Path)
    a = ap.parse_args()

    rows = [row(f, p) for f, p in sorted(families().items())]
    hdr = f'{"family":8s}{"block":>8s}{"pool":>8s}{"stored":>8s}{"miss":>6s}  rho median [min, max]'
    print(hdr)
    print("-" * len(hdr))
    for r in rows:
        flag = "" if r["n_pool"] == r["stored_pool"] else "   <-- POOL MISMATCH"
        print("%-8s%8s%8s%8s%6d  %+.3f [%+.3f, %+.3f]%s"
              % (r["family"], f'{r["n_block"]:,}', f'{r["n_pool"]:,}',
                 f'{r["stored_pool"]:,}', r["missing_entries"],
                 r["rho_median"], r["rho_min"], r["rho_max"], flag))
    assoc = coupling_vs_gain(rows)
    print("\ncoupling vs family gain (post-hoc, n=%d):" % len(assoc["families"]))
    for arm in ("pooled", "mt"):
        print("   %-6s Spearman %+.3f  p=%.3f" % (arm, assoc[arm]["rho"], assoc[arm]["p"]))

    if a.tex:
        a.tex.parent.mkdir(parents=True, exist_ok=True)
        a.tex.write_text(tex(rows), encoding="utf-8")
        mac = a.tex.with_name("macros_families.tex")
        mac.write_text(macros(assoc), encoding="utf-8")
        print(f"\nwrote {a.tex} and {mac}")


if __name__ == "__main__":
    main()
