"""Fitted multitask coupling under measured and permuted fits, per family.

    python scripts/coupling_by_family.py --tex report/generated/macros_coupling.tex

The crossed experiment (control C2) stores, for every primary state a
campaign visits, the parameters fitted on measured (M) and on permuted (P)
auxiliary responses. The coupling r in those states is what lets conditioning
responses reach the primary posterior, so it is the quantity that explains
the fitting-by-conditioning interaction. This reads it back from the stored
runs and relates it to the family's measured pairwise activity correlation.

Each campaign contributes the mean over its states, and each family the mean
over its campaigns, so long campaigns are not over-weighted. The rank
correlations are post-hoc over six families and are descriptive.
"""

from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from family_table import families, row  # noqa: E402

CROSSED = ROOT / "results" / "crossed_auxiliary_v1" / "full"


def fitted_coupling(fam: str) -> dict:
    """Mean fitted r under M and P fits, averaged within then across campaigns."""
    m, p, zero = [], [], []
    for f in sorted(glob.glob(str(CROSSED / fam / "*.json"))):
        d = json.loads(Path(f).read_text(encoding="utf-8"))
        states = list(d["parameter_states"].values())
        m.append(np.mean([s["donors"]["M"]["rho"] for s in states]))
        p.append(np.mean([s["donors"]["P"]["rho"] for s in states]))
        zero.append(np.mean([s["donors"]["P"]["rho"] == 0.0 for s in states]))
    assert m, f"no crossed runs for {fam}"
    return {"r_measured": float(np.mean(m)), "r_permuted": float(np.mean(p)),
            "permuted_zero_frac": float(np.mean(zero)), "campaigns": len(m)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tex", type=Path)
    a = ap.parse_args()

    summary = json.loads((CROSSED / "summary.json").read_text(encoding="utf-8"))
    corr = {r["family"].lower(): r["rho_median"]
            for r in (row(f, p) for f, p in sorted(families().items()))}
    fams = sorted(summary["families"])
    assert set(fams) == set(corr), (fams, sorted(corr))

    fit = {f: fitted_coupling(f) for f in fams}
    rm = [fit[f]["r_measured"] for f in fams]
    rp = [fit[f]["r_permuted"] for f in fams]
    rho = [corr[f] for f in fams]
    cond = [summary["families"][f]["contrasts"]["response_measured_fit"] for f in fams]
    inter = [summary["families"][f]["contrasts"]["interaction"] for f in fams]

    s_fit = spearmanr(rho, rm)
    s_cond = spearmanr(rm, cond)
    s_inter = spearmanr(rho, inter)
    for f in fams:
        print("%-5s corr %.2f  r_M %.3f  r_P %.3f  (r_P=0 in %.0f%% of states)  MM-MP %+.2f  D_FC %+.2f"
              % (f.upper(), corr[f], fit[f]["r_measured"], fit[f]["r_permuted"],
                 100 * fit[f]["permuted_zero_frac"],
                 summary["families"][f]["contrasts"]["response_measured_fit"],
                 summary["families"][f]["contrasts"]["interaction"]))
    print("r_M vs correlation: Spearman %+.3f p=%.3f" % (s_fit.statistic, s_fit.pvalue))
    print("MM-MP vs r_M:       Spearman %+.3f p=%.3f" % (s_cond.statistic, s_cond.pvalue))
    print("D_FC vs correlation: Spearman %+.3f p=%.3f" % (s_inter.statistic, s_inter.pvalue))

    if a.tex:
        lo, hi = int(np.argmin(rm)), int(np.argmax(rm))
        L = ["% Generated by scripts/coupling_by_family.py -- do not edit.",
             f"\\newcommand{{\\couplingMeasured}}{{${np.mean(rm):.2f}$}}",
             f"\\newcommand{{\\couplingMeasuredMin}}{{${min(rm):.2f}$}}",
             f"\\newcommand{{\\couplingMeasuredMax}}{{${max(rm):.2f}$}}",
             f"\\newcommand{{\\couplingMeasuredLowFamily}}{{{fams[lo].upper()}}}",
             f"\\newcommand{{\\couplingMeasuredHighFamily}}{{{fams[hi].upper()}}}",
             f"\\newcommand{{\\couplingLowFamilyCorr}}{{${rho[lo]:.2f}$}}",
             f"\\newcommand{{\\couplingHighFamilyCorr}}{{${rho[hi]:.2f}$}}",
             f"\\newcommand{{\\couplingPermuted}}{{${np.mean(rp):.2f}$}}",
             f"\\newcommand{{\\couplingPermutedZeroPct}}"
             f"{{${100 * np.mean([fit[f]['permuted_zero_frac'] for f in fams]):.0f}\\%$}}",
             f"\\newcommand{{\\couplingVsCorr}}{{${s_fit.statistic:+.2f}$}}",
             f"\\newcommand{{\\condVsCoupling}}{{${s_cond.statistic:+.2f}$}}",
             f"\\newcommand{{\\interVsCorr}}{{${s_inter.statistic:+.2f}$}}"]
        a.tex.parent.mkdir(parents=True, exist_ok=True)
        a.tex.write_text("\n".join(L) + "\n", encoding="utf-8")
        print(f"wrote {a.tex}")


if __name__ == "__main__":
    main()
